/// Translate with `{name}` interpolation. Unknown keys echo back.
pub fn t(lang: Lang, key: &str, args: &[(&str, &str)]) -> String {
    let (en, hi) = entry(key).unwrap_or((key, key));
    let mut out = match lang {
        Lang::En => en,
        Lang::Hi => hi,
    }
    .to_string();
    for (name, value) in args {
        out = out.replace(&format!("{{{name}}}"), value);
    }
    out
}

